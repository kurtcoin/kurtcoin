function getSystemLanguage() {
  const savedLang = localStorage.getItem('kurtcoin_user_lang');
  if (savedLang === 'tr' || savedLang === 'en') return savedLang;
  const navLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  if (navLang.startsWith('tr')) return 'tr';
  return 'en';
}

let currentLang = getSystemLanguage();

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('kurtcoin_user_lang', lang);
  applyTranslations();
  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) langBtn.innerText = currentLang === 'tr' ? '🇹🇷 TR' : '🇬🇧 EN';
}

function toggleLanguage() {
  setLanguage(currentLang === 'tr' ? 'en' : 'tr');
}

function applyTranslations() {
  const t = KURT_TRANSLATIONS[currentLang] || KURT_TRANSLATIONS.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else {
        el.innerText = t[key];
      }
    }
  });
}
